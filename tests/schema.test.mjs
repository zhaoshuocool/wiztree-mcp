import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, writeFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";

const csv = 'Generated by WizTree\nFile Name,Size,Allocated,Modified,Attributes,Files,Folders\n"C:\\Data\\",3,4096,2000-01-01,D,1,0\n"C:\\Data\\a.txt",1,4096,2000-01-01,,,\n"C:\\Data\\b.md",2,4096,2000-01-01,,,\n';

async function connect(t) {
  const transport = new StdioClientTransport({
    command: process.execPath,
    args: ["dist/index.js"],
    env: { ...process.env, WIZTREE_MCP_DISABLE_CLEANUP: "1" },
    stderr: "pipe",
  });
  const client = new Client({ name: "schema-test", version: "1" });
  await client.connect(transport);
  t.after(() => client.close());
  return client;
}

test("published tool schemas stay plain boolean and integer", async t => {
  const client = await connect(t);
  const { tools } = await client.listTools();
  const scan = tools.find((tool) => tool.name === "scan_path").inputSchema.properties;
  for (const key of ["includeFiles", "includeFolders", "admin", "treemap", "saveSnapshot"]) {
    assert.equal(scan[key].type, "boolean", `${key} must publish one obvious type`);
    assert.equal(scan[key].anyOf, undefined, `${key} must not widen into anyOf`);
  }
  assert.equal(scan.maxEntries.type, "integer");
  assert.equal(scan.maxEntries.default, 100000);
  assert.equal(scan.maxEntries.maximum, 200000);
  assert.equal(scan.includeFiles.default, true);
});

test("stringified scalars are coerced, invented spellings still fail", async t => {
  const base = await mkdtemp(join(tmpdir(), "wiztree-schema-"));
  t.after(() => rm(base, { recursive: true, force: true }));
  const csvPath = join(base, "snapshot.csv");
  await writeFile(csvPath, csv);
  const client = await connect(t);

  const narrow = await client.callTool({ name: "extension_summary", arguments: { csvPath, limit: "1" } });
  assert.notEqual(narrow.isError, true, String(narrow.content?.[0]?.text));
  const wide = await client.callTool({ name: "extension_summary", arguments: { csvPath, limit: "9" } });
  assert.notEqual(wide.isError, true, String(wide.content?.[0]?.text));
  const lineCount = (result) => String(result.content[0].text).trim().split("\n").length;
  assert.equal(lineCount(narrow), 2, '"1" must behave like the number 1');
  assert.ok(lineCount(wide) > lineCount(narrow), "the coerced limit must actually apply");

  const wrongNames = await client.callTool({
    name: "scan_path",
    arguments: { path: base, include_files: true, max_depth: 3, timeout: 120 },
  });
  assert.equal(wrongNames.isError, true);
  assert.match(String(wrongNames.content[0].text), /targetPath/, "the error must name the real parameter");

  const notANumber = await client.callTool({ name: "extension_summary", arguments: { csvPath, limit: "two" } });
  assert.equal(notANumber.isError, true);
  assert.match(String(notANumber.content[0].text), /limit/);
});
