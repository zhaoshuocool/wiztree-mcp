test("WizTree lookup prefers known install locations over PATH", t => {
  const originalPath = process.env.PATH;
  const originalProgramFiles = process.env.ProgramFiles;
  const originalProgramFilesX86 = process.env["ProgramFiles(x86)"];
  t.after(() => {
    process.env.PATH = originalPath;
    for (const [key, value] of [["ProgramFiles", originalProgramFiles], ["ProgramFiles(x86)", originalProgramFilesX86]]) {
      if (value === undefined) delete process.env[key]; else process.env[key] = value;
    }
  });
  const planted = process.platform === "win32" ? "C:\\planted-on-path" : "/planted-on-path";
  const programFiles = process.platform === "win32" ? "C:\\real-programfiles" : "/real-programfiles";
  process.env.PATH = planted;
  process.env.ProgramFiles = programFiles;
  process.env["ProgramFiles(x86)"] = `${programFiles}-x86`;
  const candidates = findWizTreeCandidates();
  const installed = candidates.findIndex(path => path === join(programFiles, "WizTree", "WizTree64.exe"));
  const fromPath = candidates.findIndex(path => path === join(planted, "WizTree64.exe"));
  assert.ok(installed >= 0 && fromPath >= 0, `expected both candidates, got ${candidates.slice(0, 6)}`);
  assert.ok(installed < fromPath, "a PATH hit must not outrank the real installation");
});

