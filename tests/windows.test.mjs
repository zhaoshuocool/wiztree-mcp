// node_modules holds 100 bytes in 3 files; the two folder rows carry 160 bytes of
// container size on top, which is what the old single "total size" summed to.
const overlapCsv = "Generated by WizTree\n" +
  "File Name,Size,Allocated,Modified,Attributes,Files,Folders\n" +
  '"C:\\Repo\\node_modules\\",100,0,2000-01-01,D,3,1\n' +
  '"C:\\Repo\\node_modules\\pkg\\",60,0,2000-01-01,D,2,0\n' +
  '"C:\\Repo\\node_modules\\pkg\\a.js",40,0,2000-01-01,,,\n' +
  '"C:\\Repo\\node_modules\\pkg\\b.js",20,0,2000-01-01,,,\n' +
  '"C:\\Repo\\node_modules\\c.js",40,0,2000-01-01,,,\n';

async function connectServer(t, env) {
  const transport = new StdioClientTransport({ command: process.execPath, args: ["dist/index.js"],
    env: { ...process.env, WIZTREE_MCP_DISABLE_CLEANUP: "1", ...env }, stderr: "pipe" });
  const client = new Client({ name: "windows-tool-test", version: "1" });
  await client.connect(transport); t.after(() => client.close());
  return client;
}
const toolText = (result) => String(result.content?.[0]?.text ?? "");

test("search_entries keeps folder container bytes out of the file total", async t => {
  const base = await setup(t);
  const csvPath = join(base, "overlap.csv");
  await writeFile(csvPath, overlapCsv);
  const client = await connectServer(t);

  const all = await client.callTool({ name: "search_entries", arguments: { csvPath, query: "node_modules" } });
  assert.equal(all.isError, undefined, toolText(all));
  const allText = toolText(all);
  assert.match(allText, /^Matches: 5 rows \(3 files, 2 folders\), files total: 100 B \(100 bytes\), folders total: 160 B \(160 bytes\), showing top 5/, allText);
  assert.doesNotMatch(allText, /260/, "folder rows and their files must not be summed together");
  assert.match(allText, /only the files total is space you could reclaim/, allText);

  const files = await client.callTool({ name: "search_entries", arguments: { csvPath, query: "node_modules", kind: "files" } });
  assert.match(toolText(files), /^Matches: 3 files, files total: 100 B \(100 bytes\), showing top 3/);
  assert.doesNotMatch(toolText(files), /folders total/, "kind=files matched no folder rows");

  const folders = await client.callTool({ name: "search_entries", arguments: { csvPath, query: "node_modules", kind: "folders" } });
  assert.match(toolText(folders), /^Matches: 2 rows \(0 files, 2 folders\), folders total: 160 B \(160 bytes\), showing top 2/);
  assert.match(toolText(folders), /not additive/, toolText(folders));
});

test("list_snapshots defaults to the export directory and honours an explicit snapshotDirectory", async t => {
  const base = await setup(t);
  const exportsDir = join(base, "exports");
  const savedDir = join(base, "saved");
  await mkdir(exportsDir); await mkdir(savedDir);
  await writeFile(join(exportsDir, "default.csv"), csv);
  await writeFile(join(savedDir, "saved.csv"), csv);
  await mkdir(join(savedDir, "a-directory.csv"));
  const client = await connectServer(t, { WIZTREE_MCP_EXPORT_DIR: exportsDir });
  const firstLine = (result) => toolText(result).split("\n")[0];

  // A snapshot saved elsewhere used to be invisible here, which read as lost data.
  const listed = await client.callTool({ name: "list_snapshots", arguments: {} });
  assert.match(firstLine(listed), /^1 snapshot\(s\) in .*exports$/, firstLine(listed));
  assert.match(toolText(listed), /default\.csv/);
  assert.doesNotMatch(toolText(listed), /saved\.csv/);

  const explicit = await client.callTool({ name: "list_snapshots", arguments: { snapshotDirectory: savedDir } });
  assert.equal(explicit.isError, undefined, toolText(explicit));
  assert.match(firstLine(explicit), /^1 snapshot\(s\) in .*saved$/, firstLine(explicit));
  assert.match(toolText(explicit), /saved\.csv/);
  assert.doesNotMatch(toolText(explicit), /default\.csv/);
  assert.doesNotMatch(toolText(explicit), /a-directory\.csv/, "a directory is not a snapshot");

  const missing = await client.callTool({ name: "list_snapshots", arguments: { snapshotDirectory: join(base, "absent") } });
  assert.equal(missing.isError, true, "a typo must not report an empty snapshot list");
  assert.match(toolText(missing), /Snapshot directory not found/);
});
