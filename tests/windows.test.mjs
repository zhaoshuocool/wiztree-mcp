test("separator collapsing keeps UNC prefixes and drill_down still matches them", async t => {
  assert.equal(collapseSeparators('C:\\\\Windows\\\\system32\\'), 'C:\\Windows\\system32\\');
  assert.equal(collapseSeparators('\\\\fs01\\share\\docs\\'), '\\\\fs01\\share\\docs\\');

  const base = await setup(t);
  const csvPath = join(base, "unc.csv");
  await writeFile(csvPath,
    "File Name,Size,Allocated,Modified,Attributes,Files,Folders\n" +
    '"\\\\fs01\\share\\docs\\",5,4096,2026-01-01,D,1,0\n' +
    '"\\\\fs01\\share\\docs\\a.txt",5,4096,2026-01-01,,,\n');
  const entries = await parseCsvStream(csvPath);
  assert.deepEqual(entries.map(entry => entry.path),
    ['\\\\fs01\\share\\docs\\', '\\\\fs01\\share\\docs\\a.txt']);
  const result = drillDown(entries, '\\\\fs01\\share\\docs', 10);
  assert.equal(result.found, true, "a UNC folder must be drillable");
  assert.deepEqual(result.children.map(entry => entry.path), ['\\\\fs01\\share\\docs\\a.txt']);
});

test("isWithin admits the export directory and refuses traversal or siblings", () => {
  const windows = process.platform === "win32";
  const root = windows ? "C:\\Repo\\exports" : "/repo/exports";
  const inside = windows ? "C:\\Repo\\exports\\treemap.png" : "/repo/exports/treemap.png";
  assert.equal(isWithin(root, inside), true);
  assert.equal(isWithin(root + (windows ? "\\" : ""), inside), true, "trailing separator must not matter");
  assert.equal(isWithin(root, windows ? "C:\\Repo\\other\\treemap.png" : "/repo/other/treemap.png"), false);
  assert.equal(isWithin(root, windows ? "C:\\Repo\\exports2\\treemap.png" : "/repo/exports2/treemap.png"), false);
  assert.equal(isWithin(root, windows ? "C:\\Repo\\exports\\..\\..\\Windows\\a.png" : "/repo/exports/../../etc/a.png"), false);
  if (windows) assert.equal(isWithin(root, "c:\\repo\\EXPORTS\\Treemap.PNG"), true, "compare case-insensitively on Windows");
});

